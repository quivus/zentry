export const payroll: PayrollRow[] = employees.map((person) => {
  const deductions = Math.round(person.salary / 12 * 0.28)
  const gross = Math.round(person.salary / 12)
  return {
    employeeId: person.id,
    gross,
    deductions,
    net: gross - deductions,
    status: person.id === 'e12' || person.id === 'e17' ? 'queued' : 'processed',
  }
})

export function findEmployee(id: string) {
  return employees.find((person) => person.id === id)
}
